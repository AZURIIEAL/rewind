using System.Text;
using Rewind.Core.Archiving;

namespace Rewind.Cli.Commands;

public static class GenerateTestCommand
{
    public static async Task<int> RunAsync(string[] args)
    {
        var (filePath, options) = CliArgs.ParsePathAndOptions(args);
        if (filePath is null)
        {
            Console.Error.WriteLine("Usage: rewind generate-test <file.rewind> [--output <path.cs>] [--namespace <ns>] [--entry-point <type>]");
            return 1;
        }

        var reader = new RewindArchiveReader();
        var contents = await reader.ReadAsync(filePath);
        SnapshotRequest.WarnIfBodyOmitted(contents);

        var className = ClassName(contents);
        var outputPath = options.GetValueOrDefault("output", $"{className}.cs");
        var code = Build(
            contents,
            options.GetValueOrDefault("namespace", "RewindReplays"),
            options.GetValueOrDefault("entry-point", "Program"));

        await File.WriteAllTextAsync(outputPath, code);
        Console.WriteLine($"Wrote {outputPath}");
        Console.WriteLine("""
            Add it to a test project that references your API project and these packages:
              xunit, Microsoft.AspNetCore.Mvc.Testing
            If your API uses top-level statements, add `public partial class Program { }` to it
            so the test project can see Program. The test fails while the bug reproduces.
            """);

        return 0;
    }

    public static string ClassName(RewindArchiveContents contents)
    {
        var id = new string(contents.Manifest.Id.Where(char.IsLetterOrDigit).ToArray());
        return $"RewindReplay_{id[..Math.Min(8, id.Length)]}Tests";
    }

    public static string Build(RewindArchiveContents contents, string @namespace, string entryPoint)
    {
        var http = contents.HttpContext;
        var manifest = contents.Manifest;
        var className = ClassName(contents);
        var exceptionName = Identifier(manifest.ExceptionType?.Split('.').Last() ?? "Exception");

        var builder = new StringBuilder();
        builder.AppendLine($"// <auto-generated> by `rewind generate-test` from snapshot {manifest.Id} </auto-generated>");
        builder.AppendLine("using System.Net.Http.Headers;");
        builder.AppendLine("using Microsoft.AspNetCore.Mvc.Testing;");
        builder.AppendLine("using Xunit;");
        builder.AppendLine();
        builder.AppendLine($"namespace {@namespace};");
        builder.AppendLine();
        builder.AppendLine("/// <summary>");
        builder.AppendLine($"/// Replays the request captured in Rewind snapshot {manifest.Id}.");
        builder.AppendLine($"/// Captured {manifest.Timestamp:O} in {manifest.Environment}: {OneLine(manifest.ExceptionType)}: {OneLine(manifest.ExceptionMessage)}");
        builder.AppendLine("/// Fails while the bug reproduces; passes once it's fixed. Debug it to hit your breakpoints.");
        builder.AppendLine("/// </summary>");
        builder.AppendLine($"public class {className} : IClassFixture<WebApplicationFactory<{entryPoint}>>");
        builder.AppendLine("{");
        builder.AppendLine($"    private readonly WebApplicationFactory<{entryPoint}> _factory;");
        builder.AppendLine();
        builder.AppendLine($"    public {className}(WebApplicationFactory<{entryPoint}> factory) => _factory = factory;");
        builder.AppendLine();
        builder.AppendLine("    [Fact]");
        builder.AppendLine($"    public async Task Replay_{exceptionName}_DoesNotFail()");
        builder.AppendLine("    {");
        builder.AppendLine("        using var client = _factory.CreateClient();");
        builder.AppendLine($"        using var request = new HttpRequestMessage(new HttpMethod({Literal(http.Method)}), {Literal(SnapshotRequest.PathAndQuery(http))});");

        foreach (var (key, value) in SnapshotRequest.ForwardableHeaders(http))
        {
            builder.AppendLine($"        request.Headers.TryAddWithoutValidation({Literal(key)}, {Literal(value)});");
        }

        if (!string.IsNullOrEmpty(contents.Payload))
        {
            builder.AppendLine("        request.Content = new StringContent(");
            AppendRawStringLiteral(builder, contents.Payload, indent: "            ");
            builder.AppendLine("        request.Content.Headers.ContentType = MediaTypeHeaderValue.Parse(" +
                               $"{Literal(SnapshotRequest.ContentType(http) ?? "application/json")});");
        }

        builder.AppendLine();
        builder.AppendLine("        using var response = await client.SendAsync(request);");
        builder.AppendLine();
        builder.AppendLine("        Assert.True((int)response.StatusCode < 500,");
        builder.AppendLine("            $\"Replayed request failed with {(int)response.StatusCode}: {await response.Content.ReadAsStringAsync()}\");");
        builder.AppendLine("    }");
        builder.AppendLine("}");

        return builder.ToString();
    }

    // A multi-line raw string literal can hold any payload verbatim, as long as its delimiter has more
    // quotes than the longest run of quotes inside the payload.
    private static void AppendRawStringLiteral(StringBuilder builder, string payload, string indent)
    {
        var longestQuoteRun = 0;
        var currentRun = 0;
        foreach (var c in payload)
        {
            currentRun = c == '"' ? currentRun + 1 : 0;
            longestQuoteRun = Math.Max(longestQuoteRun, currentRun);
        }

        var delimiter = new string('"', Math.Max(3, longestQuoteRun + 1));
        builder.AppendLine($"{indent}{delimiter}");
        foreach (var line in payload.ReplaceLineEndings("\n").Split('\n'))
        {
            builder.AppendLine(line.Length == 0 ? string.Empty : indent + line);
        }

        builder.AppendLine($"{indent}{delimiter});");
    }

    private static string Literal(string value)
    {
        var builder = new StringBuilder("\"");
        foreach (var c in value)
        {
            builder.Append(c switch
            {
                '\\' => @"\\",
                '"' => "\\\"",
                '\n' => @"\n",
                '\r' => @"\r",
                '\t' => @"\t",
                '\0' => @"\0",
                _ => c.ToString()
            });
        }

        return builder.Append('"').ToString();
    }

    private static string Identifier(string value)
    {
        var identifier = new string(value.Where(char.IsLetterOrDigit).ToArray());
        return identifier.Length == 0 || char.IsDigit(identifier[0]) ? "_" + identifier : identifier;
    }

    private static string OneLine(string? value) => (value ?? string.Empty).ReplaceLineEndings(" ");
}
